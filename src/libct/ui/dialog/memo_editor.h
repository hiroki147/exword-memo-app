#ifndef MEMO_EDITOR_H
#define MEMO_EDITOR_H

/**
 * @brief 複数行のメモ本文を編集するエディタ画面を表示する。
 *
 * 操作方法:
 *   [A-Z]       : 文字入力（[Kana]モード時はローマ字入力→半角カタカナ変換）
 *   [SHIFT]     : 英字入力(EN) / かな入力(Kana) の切り替え
 *   [SYMBOL]    : スペース入力
 *   [ENTER]     : 改行
 *   [BACKSPACE] : 1文字削除（ローマ字入力中はまずローマ字側を1文字削除）
 *   [FUNC1(F1)] : 保存して終了
 *   [POWER]     : 保存して終了（データ消失防止のため）
 *   [BACK]      : 確認の上、編集を破棄してキャンセル
 *
 * かな入力は半角カタカナのみ対応（ひらがな・漢字非対応）。
 * ローマ字は「KA」→ｶ のように1〜3打鍵で1文字に変換される。
 * 濁音・半濁音は基本音+濁点/半濁点の組み合わせで表現される（例: "GA"→ｶﾞ）。
 * 促音は子音の連続で自動挿入されるほか、"XTU"でも入力できる。
 * 撥音「ん」は "NN" で入力できる（単独の"N"は、次に母音以外が続くと自動的に確定する）。
 *
 * @param initial_text 初期表示するテキスト。NULLの場合は空文字から開始する。
 * @return 編集後のテキストへのポインタ（内部staticバッファ）。
 *         キャンセルされた場合はNULLを返す。
 * @note 戻り値は次回呼び出しまで有効。呼び出し側で解放する必要はない。
 */
char *memo_editor(const char *initial_text);

#endif /* MEMO_EDITOR_H */
